package xray

import (
	"os"
	"os/exec"
	"path/filepath"
	"strings"
	"testing"

	"github.com/levvs-one/sora-client/core/engine"
	"github.com/levvs-one/sora-client/core/engine/enginetest"
)

// TestBinaryAcceptsCatalogFloorCorpus is the binary-pinned proof
// behind the Xray catalog floor (LEGACY-FULL WS2): every config the
// floor's claims depend on — REALITY/Vision, the full XHTTP set
// (xmux + padding + download split), VLESS Encryption, the ECH
// spellings, TLS fragmentation and the Hysteria2 render (plain and
// with brutal bandwidth hints) — must be accepted by `run -test` on
// a real Xray binary, and the binary's version must be at or above
// the catalog floor. The floor exists because the previous payload
// build (25.9.11) has no Hysteria outbound at all (added upstream
// by PR 5508, first tagged in v26.1.13): pointed at such a binary
// this test fails
// on the Hysteria2 configs, which is exactly the regression it
// guards. ECH is lazy-validated by Xray's loader, so its configs
// are only run -test-accepted here; the field's presence in the
// binary is asserted by symbol search as a supplement, and the
// wire effect stays unclaimed for this pin (see catalog.go).
func TestBinaryAcceptsCatalogFloorCorpus(t *testing.T) {
	bin := os.Getenv("SORA_XRAY_BIN")
	if bin == "" {
		dir := os.Getenv("SORA_ENGINES_DIR")
		if dir == "" {
			t.Skip("set SORA_ENGINES_DIR or SORA_XRAY_BIN to check the floor corpus with Xray")
		}
		bin = filepath.Join(dir, "xray")
	}
	verOut, err := exec.CommandContext(t.Context(), bin, "version").Output()
	if err != nil {
		t.Fatalf("xray version: %v", err)
	}
	// "Xray 26.3.27 (Xray, Penetrates Everything.) ..."
	fields := strings.Fields(string(verOut))
	if len(fields) < 2 {
		t.Fatalf("unparseable xray version output: %q", verOut)
	}
	ver, err := engine.ParseVersion(fields[1])
	if err != nil {
		t.Fatalf("parse xray version %q: %v", fields[1], err)
	}
	floor, err := engine.ParseVersion(engine.Catalog[engine.KindXray].MinVersion)
	if err != nil {
		t.Fatal(err)
	}
	if ver.Less(floor) {
		t.Fatalf("xray %s is below the catalog floor %s: the floor corpus is not expected to pass (25.9.11 has no hysteria outbound)", ver, floor)
	}

	hy2 := enginetest.Plan(engine.ProtocolHysteria2)
	hy2.Outbounds[0].Obfs, hy2.Outbounds[0].ObfsParam = "", ""
	hy2Brutal := enginetest.Plan(engine.ProtocolHysteria2)
	hy2Brutal.Outbounds[0].Obfs, hy2Brutal.Outbounds[0].ObfsParam = "", ""
	hy2Brutal.Outbounds[0].UpMbps, hy2Brutal.Outbounds[0].DownMbps = 100, 500

	xhttp := enginetest.Plan(engine.ProtocolVLESS)
	xhttp.Outbounds[0].Flow = ""
	xhttp.Outbounds[0].TLS = engine.TLS{Enabled: true, ServerName: "cdn.example.com", Fingerprint: "chrome"}
	xhttp.Outbounds[0].Transport = engine.Transport{
		Type: "xhttp", Path: "/xhttp", Host: "cdn.example.com", Mode: "stream-up",
		XPaddingBytes: "100-1000", XmuxMaxConnections: 4, XmuxMaxRequestTimes: 100,
		DownloadAddress: "dl.example.com", DownloadPort: 8443,
	}

	enc := enginetest.Plan(engine.ProtocolVLESS)
	enc.Outbounds[0].Flow = ""
	enc.Outbounds[0].TLS = engine.TLS{Enabled: true, ServerName: "cdn.example.com"}
	enc.Outbounds[0].Encryption = "mlkem768x25519plus.native.0rtt.iA0A13jrnXO-dKlbhMsII3xQkOu3OIRJ86tA7rBreTs"

	echPinned := enginetest.Plan(engine.ProtocolTrojan)
	// A real list, generated by the sing-box pin's `generate
	// ech-keypair public.example.com` (same list as LEGACY-PLAT-OBFS).
	echPinned.Outbounds[0].TLS.ECH = engine.ECHConfig{Enabled: true, Config: []string{
		"-----BEGIN ECH CONFIGS-----",
		"AE3+DQBJAAAgACDO8jfw6QzRlv3jU0M3MzhAZwWOaWbbinfiJhvhyK2DDwAMAAEA",
		"AQABAAIAAQADABJwdWJsaWMuZXhhbXBsZS5jb20AAA==",
		"-----END ECH CONFIGS-----",
	}}
	echUnpinned := enginetest.Plan(engine.ProtocolTrojan)
	echUnpinned.Outbounds[0].TLS.ECH = engine.ECHConfig{Enabled: true}

	frag := enginetest.Plan(engine.ProtocolVLESS)
	frag.Options.Fragment = engine.Fragment{Enabled: true}

	corpus := map[string]*engine.Plan{
		"reality-vision":   enginetest.Plan(engine.ProtocolVLESS),
		"xhttp-full":       xhttp,
		"vless-encryption": enc,
		"ech-pinned":       echPinned,
		"ech-unpinned":     echUnpinned,
		"fragment":         frag,
		"hysteria2":        hy2,
		"hysteria2-brutal": hy2Brutal,
		"wireguard":        enginetest.Plan(engine.ProtocolWireGuard),
		"ss2022":           enginetest.Plan(engine.ProtocolShadowsocks),
	}
	for name, plan := range corpus {
		raw, err := Render(plan, testRuntime, nil)
		if err != nil {
			t.Fatalf("%s: render: %v", name, err)
		}
		cfg := filepath.Join(t.TempDir(), "config.json")
		if err := os.WriteFile(cfg, raw, 0o600); err != nil {
			t.Fatal(err)
		}
		// run -test resolves geoip/geosite next to the binary.
		cmd := exec.CommandContext(t.Context(), bin, "run", "-test", "-c", cfg)
		cmd.Dir = filepath.Dir(bin)
		if out, err := cmd.CombinedOutput(); err != nil {
			t.Errorf("%s: xray %s refused the floor-corpus render: %v\n%s\n--- render ---\n%s", name, ver, err, out, raw)
		}
	}

	// Lazy-validated ECH fields: supplement the run -test pass with
	// symbol presence, the method LEGACY-PLAT-OBFS used on 25.9.11.
	raw, err := os.ReadFile(bin)
	if err != nil {
		t.Fatal(err)
	}
	for _, sym := range []string{"echConfigList", "echForceQuery", "mlkem768x25519plus"} {
		if !strings.Contains(string(raw), sym) {
			t.Errorf("xray %s binary does not contain %q", ver, sym)
		}
	}
	// Negative control: the bogus-fingerprint REALITY render must be
	// refused, proving run -test really builds the outbound.
	bogus := enginetest.Plan(engine.ProtocolVLESS)
	bogus.Outbounds[0].TLS.Fingerprint = "bogus-fp"
	rawBogus, err := Render(bogus, testRuntime, nil)
	if err != nil {
		t.Fatal(err)
	}
	cfg := filepath.Join(t.TempDir(), "bogus.json")
	if err := os.WriteFile(cfg, rawBogus, 0o600); err != nil {
		t.Fatal(err)
	}
	cmd := exec.CommandContext(t.Context(), bin, "run", "-test", "-c", cfg)
	cmd.Dir = filepath.Dir(bin)
	if out, err := cmd.CombinedOutput(); err == nil {
		t.Errorf("xray %s accepted a bogus fingerprint; run -test is not validating:\n%s", ver, out)
	}
}
